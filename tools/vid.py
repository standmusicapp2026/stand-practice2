import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width':1366,'height':1024}, has_touch=True); pg = await ctx.new_page()
        await pg.add_init_script('window.__noTour = true;')
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('http://localhost:' + __import__('os').environ.get('PORT','8765') + '/index.html'); await pg.wait_for_timeout(1200)
        await pg.evaluate("() => { const w=document.querySelector('#welcome'); if (w && !w.hidden) document.querySelector('#welGo')?.click(); }")
        J = lambda js: pg.evaluate("async () => { const sleep=(ms)=>new Promise(r=>setTimeout(r,ms)); " + js + " }")
        await J("document.querySelector('.tour-skip')?.click(); await sleep(200); document.querySelector('.tile[data-tile=\"takes\"]').click(); await sleep(500);")
        await pg.set_input_files('#takeImportFile', '/home/claude/fixtures/clip.webm'); await pg.wait_for_timeout(5000)
        print(await J("return [...document.querySelectorAll('#takeList li')].map(l=>l.textContent)"))
        await J("document.querySelector('#takeList li')?.click(); await sleep(1500);")
        await pg.screenshot(path='/home/claude/shots/vid_sel.png')
        await J("document.querySelector('#playBtn').click(); await sleep(1500);")
        print('playing', await J("const v=document.querySelector('#takeVideo'); return [v.paused, v.currentTime, v.readyState, v.src.slice(0,20)]"))
        await J("document.querySelector('#takeFloat').click(); await sleep(800);")
        await pg.screenshot(path='/home/claude/shots/vid_float.png')
        await J("document.querySelector('#vfBig').click(); await sleep(400);")
        await pg.screenshot(path='/home/claude/shots/vid_big.png')
        await J("document.querySelector('#vfBack').click(); await sleep(600); document.querySelector('#takesScope button[data-scope=all]').click(); await sleep(400);")
        print('list visible after back', await J("return getComputedStyle(document.querySelector('#takeList')).display !== 'none' && document.querySelector('#player').hidden"))
        await J("document.querySelector('#takeList li')?.click(); await sleep(800); document.querySelector('#panel-takes [data-close]').click(); await sleep(300); document.querySelector('.tile[data-tile=\"takes\"]').click(); await sleep(500);")
        print('reopen shows list', await J("return document.querySelector('#player').hidden"))
        print('errors', errs)
        await b.close()
asyncio.run(main())
